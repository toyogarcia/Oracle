# Generar JSON desde una consulta
#   NOTA: JSON_OBJECT puede devolver VARCHAR2 or CLOB. Por defecto devuelve VARCHAR2, que puede generar una excepcion overflow exception si el tamaño del objeto supera los 4000 bytes (or 32000 bytes).

SELECT JSON_OBJECT(
    'id' VALUE id,
    'nombre' VALUE nombre,
    'datos' VALUE datos
) AS producto_json
FROM productos;

# Agrupar los valores de filas de una consulta SQL y convertirlos en una única matriz JSON

SELECT JSON_ARRAYAGG(e.first_name ORDER BY e.first_name) AS employee_array 
FROM employees e 
WHERE e.department_id = 20;

