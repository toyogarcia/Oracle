# JSON_OBJECT_T: Puede usarse para generar y parsear datos JSON.
# Uso directo: 
#   Crear nuevo par key-value usando el tipo JSON_OBJECT_T e invocando al metodo put. 
#   Crear nuevo array usando el tipo JSON_ARRAY_T.
# El parseado es incluso más directo: Pasa los datos JSON a la función parse y JSON_OBJECT_T la maneja por ti. Una vez parseado puedes acceder a los datos usando keys.
# Usando JSON_OBJECT_T no se necesitan paths, sin embargo se necesita logica adicional para almacenar los datos del JSON parseado en una tabla.

DECLARE
  l_json JSON_OBJECT_T;
  l_courses JSON_ARRAY_T;
  l_addresses JSON_OBJECT_T;
  l_addresses_arr JSON_ARRAY_T;
  
  l_keys JSON_KEY_LIST;
  l_value JSON_ARRAY_T;
   l_json_object JSON_OBJECT_T;
BEGIN
  -- Create a new object.
  l_json := JSON_OBJECT_T();

  -- Add a new element to the object.
  l_json.put('name', 'Robert');
  l_json.put('age', 23);
  l_json.put('isStudent', 'false');

  -- Create courses array
  l_courses := JSON_ARRAY_T();
  l_courses.append('Math');
  l_courses.append('Science');
  l_courses.append('Music');
  -- Add courses to object
  l_json.put('courses', l_courses);

  -- Create addresses array
  l_addresses_arr := JSON_ARRAY_T();
  -- Create addresses object
  l_addresses := JSON_OBJECT_T();
  l_addresses.put('city','New York');
  l_addresses.put('zip','10001');
  -- Add to array
  l_addresses_arr.append(l_addresses);
  -- Create addresses object
  l_addresses := JSON_OBJECT_T();
  l_addresses.put('city','Boston');
  l_addresses.put('zip','02108');
  -- Add to array
  l_addresses_arr.append(l_addresses);
  -- Add addresses to object
  l_json.put('addresses', l_addresses_arr);

  
  DBMS_OUTPUT.put_line(l_json.stringify);

  DBMS_OUTPUT.put_line('Sacamos los valores:'); 

 l_json_object := JSON_OBJECT_T.parse(l_json.stringify);
  l_keys := l_json_object.get_keys;
  FOR i IN 1..l_keys.COUNT LOOP
    IF l_json_object.get_Type(l_keys(i)) = 'SCALAR' THEN
      dbms_output.put_line(l_keys(i) || ':' || l_json_object.get_String(l_keys(i)));
    ELSE -- Array
      l_value := l_json_object.get_Array(l_keys(i));
      dbms_output.put_line(l_value.stringify);
    END IF;
  END LOOP;

END;

