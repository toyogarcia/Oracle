# JSON_MERGEPATCH

UPDATE productos
SET datos = JSON_MERGEPATCH(datos, '{"precio": 900}')
WHERE nombre = 'Mouse';


# JSON_TRANSFORM (21c+)

UPDATE productos
SET datos = JSON_TRANSFORM(datos, SET '$.precio' = 1500.6)
WHERE nombre = 'Teclado';

###################
# BORRADO
###################

UPDATE productos
SET datos = JSON_TRANSFORM(datos, REMOVE '$.tags')
WHERE nombre = 'Teclado';

