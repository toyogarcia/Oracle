# GENERAL

# Una API REST (o RESTful) es una interfaz digital que permite que dos sistemas de software se comuniquen entre sí a través de internet usando el protocolo HTTP.
# API (Application Programming Interface): Un conjunto de reglas que permite a una aplicación pedir datos o acciones a otra.
# REST (Representational State Transfer): Un estilo de arquitectura de software que define cómo debe estructurarse la comunicación.
# RESTful: Es el adjetivo que se usa para describir un servicio web o una API que cumple estrictamente con los principios de REST.
# La comunicación funciona mediante peticiones y respuestas usando los métodos estándar de HTTP (conocidos como operaciones CRUD):
# 	GET: Para leer u obtener información (por ejemplo, buscar el perfil de un usuario).
# 	POST: Para crear un recurso nuevo (por ejemplo, registrar una cuenta nueva).
# 	PUT: Para actualizar un registro existente.
# 	DELETE: Para eliminar datos

# Para que una API sea considerada RESTful, debe seguir normas como:
#   Cliente-servidor: El frontend (la interfaz visual) y el backend (el servidor y la base de datos) están totalmente separados.
#   Sin estado (Stateless): Cada petición del cliente debe contener toda la información necesaria para que el servidor la entienda; el servidor no guarda datos de sesiones anteriores en la memoria local.
#   Caché: Las respuestas deben indicar si pueden guardarse temporalmente para acelerar la velocidad de carga

# JSON (JavaScript Object Notation) es un formato basado en texto ligero usado para almacenar e intercambiar datos.
# JSON es un componente vita de las integraciones API. Con llamadas REST o desarrollando servicios web, es esencial entender como trabajar con JSON.
# JSON representa datos como key-value y soporta estructuras de datos como objetos (diccionarios) y arrays (listas).
# JSON juega un papel principal en REST (Representational State Transfer) APIs cimo el formato primario para intercambio de datos entre clientes y servidores.
# Cuando un cliente hace una petición (GET, POST, PUT, DELETE), el servidor responde con datos formateados en JSON, que el cliente puede parsear y procesar.
# Comparado con XML, JSON es más compacto y rápido de parsear, mejorando el rendimiento en aplicaciones web.

# Oracle Database ofrece soporte nativo para JSON desde la versión 12c
# Se puede guardar JSON en columnas de tipo VARCHAR2, CLOB, BLOB.
# Desde Oracle 21c existe un tipo de dato específico JSON.

