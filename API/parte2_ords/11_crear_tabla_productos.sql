-- ---------------------------------------------------------------------
-- PASO 11.1 - Crear la tabla
-- ---------------------------------------------------------------------
CREATE TABLE productos (
  -- Clave primaria autonumérica. "BY DEFAULT ON NULL" permite que ORDS
  -- inserte sin indicar el id y que Oracle lo genere.
  id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR2(100) NOT NULL,
  descripcion    VARCHAR2(400),
  precio         NUMBER(10,2)  NOT NULL
                 CONSTRAINT ck_productos_precio CHECK (precio >= 0),
  -- DEFAULT ON NULL: si llega NULL (o no llega), se usa el valor por defecto
  stock          NUMBER(8)     DEFAULT ON NULL 0,
  activo         VARCHAR2(1)   DEFAULT ON NULL 'S'
                 CONSTRAINT ck_productos_activo CHECK (activo IN ('S','N')),
  fecha_creacion TIMESTAMP     DEFAULT ON NULL SYSTIMESTAMP
);

